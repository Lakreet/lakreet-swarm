function escapeYaml(str) {
  if (str.includes(":") || str.includes("#") || str.includes('"') || str.includes("'")) {
    return '"' + str.replace(/"/g, '\\"') + '"';
  }
  return str;
}

function genErrors(outDir) {
  const errorsJs = readFileSync(join(ROOT, "src", "errors.js"), "utf8");

  // Parse error catalog from source
  const catalogMatch = errorsJs.match(/const CATALOG = \{([\s\S]*?)\n\};/);
  const exitMatch = errorsJs.match(/export const EXIT = \{([\s\S]*?)\n\};/);

  const errors = [];
  if (catalogMatch) {
    const catalogText = catalogMatch[1];
    const entries = catalogText.matchAll(/(\w+): \{ exitCode: EXIT\.(\w+), hint: "([^"]*)" \}/g);
    for (const m of entries) {
      errors.push({ code: m[1], exitCode: m[2], hint: m[3] });
    }
  }

  const exitCodes = [];
  if (exitMatch) {
    const exitText = exitMatch[1];
    const entries = exitText.matchAll(/(\w+): (\d+)/g);
    for (const m of entries) {
      exitCodes.push({ name: m[1], code: m[2] });
    }
  }

  // Write errors.md
  const errorsContent = `---
title: Errors
description: ${escapeYaml("Error catalog with code, cause, example message, and suggestion for each error.")}
type: reference
status: stable
since: 0.2.0
verified:
  swarm: 0.2.0
  effectcraft: 0.8.0
---

<!-- GENERATED by lakreet-swarm scripts/gen-docs.js. Do not edit. -->

# Errors

Complete error catalog from \`src/errors.js\`. Every user-facing failure is a \`SwarmError\` with stable code, exit code, and hint.

## Error catalog

| Code | Exit code | Cause | Example message | Hint |
|------|-----------|-------|-----------------|------|
${errors.map((e) => `| \`${e.code}\` | ${e.exitCode} | ${e.code.replace("E_", "").replace(/_/g, " ").toLowerCase()} | \`[varies]\` | ${e.hint} |`).join("\n")}

## Error format

\`\`\`
Error message
  Hint: suggestion
\`\`\`

Example:
\`\`\`
Found 2 problem(s) in data.csv:
- Line 5, column "Opacity": "abc" is not a number.
- Line 8, column "Logo": file not found: /path/to/missing.png
  Hint: Fix the reported rows/columns, then run again.
\`\`\`

## In --json mode

Errors appear in NDJSON \`row\` events:

\`\`\`json
{
  "event": "row",
  "index": 5,
  "where": "line 6",
  "status": "failed",
  "output": null,
  "seconds": 0,
  "error": "EffectCraft render failed with code 1"
}
\`\`\`
`;
  writeFileSync(join(outDir, "errors.md"), errorsContent);

  // Write exit-codes.md
  const exitContent = `---
title: Exit codes
description: ${escapeYaml("Table of process exit codes: 0=OK, 1=render failed, 2=usage, 3=invalid data, 4=CLI not found, 5=template unreadable, 130=interrupted.")}
type: reference
status: stable
since: 0.2.0
verified:
  swarm: 0.2.0
  effectcraft: 0.8.0
---

<!-- GENERATED by lakreet-swarm scripts/gen-docs.js. Do not edit. -->

# Exit codes

| Code | Constant | Meaning | When |
|------|----------|---------|------|
${exitCodes.map((e) => `| ${e.code} | \`${e.name}\` | ${e.name.replace(/_/g, " ").toLowerCase()} | |`).join("\n")}

## Usage in scripts

\`\`\`bash
lakreet-swarm render --template t.ectemplate --data d.csv
CODE=$?

case $CODE in
  0) echo "Success";;
  1) echo "Render failed — check report.json";;
  2) echo "Usage error — run with --help";;
  3) echo "Bad data — run check first";;
  4) echo "Install EffectCraft or set --cli";;
  5) echo "Template corrupt or unreadable";;
  130) echo "Interrupted — resume with --skip-existing";;
  *) echo "Unknown exit code: $CODE";;
esac

exit $CODE
\`\`\`

## With --fail-fast

Exit code 1 on first failure (no retry, no continue).

## With --retries

Exit code 1 only if **all retries exhausted** for a row.
`;
  writeFileSync(join(outDir, "exit-codes.md"), exitContent);
}

