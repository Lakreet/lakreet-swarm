#!/usr/bin/env node
/**
 * gen-docs.js - Generate reference documentation from source code
 * Usage: node scripts/gen-docs.js <output-folder>
 */

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const ROOT = resolve(__dirname, "..");

function runCmd(args, cwd = ROOT) {
  const result = spawnSync("node", args, { cwd, encoding: "utf8" });
  if (result.error) throw result.error;
  if (result.status !== 0 && result.status !== null) {
    // Some commands may return non-zero for --help, that's ok
  }
  return result.stdout + result.stderr;
}

function parseHelp(text) {
  const lines = text.trim().split("\n");
  const options = [];
  let inOptions = false;
  let currentOpt = null;

  for (const line of lines) {
    if (
      line.includes("Render options:") ||
      line.includes("Options:") ||
      line.includes("Global options:")
    ) {
      inOptions = true;
      continue;
    }
    if (inOptions) {
      const match = line.match(/^\s{2}(--[\w-]+)(?:\s+(.+))?/);
      if (match) {
        if (currentOpt) options.push(currentOpt);
        currentOpt = { flag: match[1], desc: (match[2] || "").trim() };
      } else if (currentOpt && line.startsWith("      ")) {
        currentOpt.desc += " " + line.trim();
      } else if (line.trim() === "" || line.startsWith("  -h") || line.startsWith("  -v")) {
        if (currentOpt) options.push(currentOpt);
        currentOpt = null;
      }
    }
  }
  if (currentOpt) options.push(currentOpt);
  return options;
}

