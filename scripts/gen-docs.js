function main() {
  const args = process.argv.slice(2);
  if (args.length !== 1) {
    console.error("Usage: node scripts/gen-docs.js <output-folder>");
    process.exit(1);
  }
  const outDir = resolve(args[0]);

  // Create output directories
  mkdirSync(join(outDir, "cli"), { recursive: true });

  console.log("Generating reference docs to:", outDir);

  // Get version
  const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
  console.log("Version:", pkg.version);

  // Generate CLI pages
  console.log("Generating CLI index...");
  const rootHelp = runCmd(["src/cli.js", "--help"]);
  genCliIndex(rootHelp, outDir);

  const commands = ["render", "check", "inspect", "init", "preview", "doctor"];
  for (const cmd of commands) {
    console.log(`Generating CLI ${cmd}...`);
    const help = runCmd(["src/cli.js", cmd, "--help"]);
    genCliCommand(cmd, help, outDir);
  }

  // Generate errors & exit codes
  console.log("Generating errors & exit-codes...");
  genErrors(outDir);

  // Generate compatibility
  console.log("Generating compatibility...");
  genCompat(outDir);

  // Generate changelog
  console.log("Generating changelog...");
  genChangelog(outDir);

  console.log("Done!");
}

main();
